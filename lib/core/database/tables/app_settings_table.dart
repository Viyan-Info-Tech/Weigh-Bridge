import 'package:drift/drift.dart';

class AppSettings extends Table {
  IntColumn get id => integer().autoIncrement()();

  // Weight
  TextColumn get weightUnit => text().withDefault(const Constant('ton'))();

  // Bill numbering
  TextColumn get billPrefix => text().withDefault(const Constant('WB'))();
  IntColumn get billStartingNumber =>
      integer().withDefault(const Constant(1))();
  IntColumn get billNumberDigits => integer().withDefault(const Constant(5))();

  // Receipt header
  TextColumn get businessName =>
      text().withDefault(const Constant('VIYAN WEIGHBRIDGE'))();
  TextColumn get businessSubtitle => text().nullable()();
  TextColumn get serviceText => text().nullable()();
  TextColumn get address => text().nullable()();
  TextColumn get phoneNumber => text().nullable()();
  TextColumn get email => text().nullable()();
  TextColumn get gstin => text().nullable()();
  TextColumn get logoPath => text().nullable()();

  // Receipt
  TextColumn get receiptTitle =>
      text().withDefault(const Constant('WEIGHMENT RECEIPT'))();

  // Receipt field visibility
  BoolColumn get showSerialNumber =>
      boolean().withDefault(const Constant(true))();
  BoolColumn get showDate => boolean().withDefault(const Constant(true))();
  BoolColumn get showTime => boolean().withDefault(const Constant(true))();
  BoolColumn get showVehicleNumber =>
      boolean().withDefault(const Constant(true))();
  BoolColumn get showGrossWeight =>
      boolean().withDefault(const Constant(true))();
  BoolColumn get showTareWeight =>
      boolean().withDefault(const Constant(true))();
  BoolColumn get showNetWeight => boolean().withDefault(const Constant(true))();
  BoolColumn get showRemarks => boolean().withDefault(const Constant(true))();

  // Footer
  BoolColumn get showFooterNote =>
      boolean().withDefault(const Constant(true))();
  TextColumn get footerNote => text().nullable()();

  // ---------------------------------------------------------------------------
  // Continuous-form (pre-printed certificate) printing
  //
  // Positions only - the HMB Enterprises logo, headings, borders and footer are
  // already on the paper and are never generated by the application.
  // ---------------------------------------------------------------------------

  /// Characters per inch: 10 or 12.
  IntColumn get printCpi => integer().withDefault(const Constant(12))();

  /// Lines per inch: 6 or 8.
  IntColumn get printLpi => integer().withDefault(const Constant(6))();

  /// Custom paper width in mm; 0 = use the size reported by the printer driver.
  RealColumn get printPaperWidthMm => real().withDefault(const Constant(0.0))();

  /// Custom paper length in mm; 0 = use the size reported by the printer driver.
  RealColumn get printPaperLengthMm =>
      real().withDefault(const Constant(0.0))();

  /// Fine horizontal nudge in mm added to the driver's printable-area offset.
  RealColumn get printLeftOffsetMm => real().withDefault(const Constant(0.0))();

  /// Fine vertical nudge in mm added to the driver's printable-area offset.
  RealColumn get printTopOffsetMm => real().withDefault(const Constant(0.0))();

  /// Distance in mm between the two copies' origins; 0 = half the paper.
  RealColumn get printColumnWidthMm =>
      real().withDefault(const Constant(0.0))();

  /// JSON grid of per-field character positions (columns/lines).
  TextColumn get printFieldGrid => text().nullable()();

  /// Print the weight unit with the value (`80.000 ton`) when the pre-printed
  /// form does not carry its own unit.
  BoolColumn get printWeightUnit =>
      boolean().withDefault(const Constant(true))();

  DateTimeColumn get updatedAt => dateTime().withDefault(currentDateAndTime)();
}
